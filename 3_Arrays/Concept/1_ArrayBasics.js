// Push() -> add new element at the end of the array
let arr4 = ['orange','apple'];
arr4.push('mango');
// console.log(arr4);


// Pop()  --> remove element from end of the array
let arr5 = ['orange','banana','guava'];
arr5.pop();
// console.log(arr5);

// Unshift() --> add element at the start of the array
let arr6 = [1,2,3,4,5,6];
arr6.unshift(0);
// console.log(arr6);

// Shift() --> remove element at the start of the array
let arr7 = [1,2,3,4,5];
arr7.shift();
// console.log(arr7);



